/// Why a /v1/systemone request failed, with the HTTP status Ollama uses for it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SystemOneError {
    /// Body is not JSON of the request's shape (400). Ollama returns Go's decoder text; ours
    /// is serde's — the status and `{"error": …}` shape match, the wording cannot.
    Bind(String),
    /// Decoded, but fails Ollama's validation (400). Message is Ollama's verbatim.
    Invalid(String),
    /// Scorer output does not fit the request (500). Message is Ollama's verbatim.
    Scorer(String),
    /// The first JSON value runs past 64 KiB (413, Ollama's message).
    TooLarge,
}

impl SystemOneError {
    /// HTTP status Ollama returns for this error.
    #[must_use]
    pub fn status(&self) -> u16 {
        match self {
            Self::Bind(_) | Self::Invalid(_) => 400,
            Self::Scorer(_) => 500,
            Self::TooLarge => 413,
        }
    }
}

impl std::fmt::Display for SystemOneError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Bind(m) | Self::Invalid(m) | Self::Scorer(m) => f.write_str(m),
            Self::TooLarge => f.write_str("request body must not exceed 64 KiB"),
        }
    }
}

impl std::error::Error for SystemOneError {}
